CREATE TABLE customers (
 customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR2(120) NOT NULL,
 email VARCHAR2(254) NOT NULL UNIQUE,
 phone VARCHAR2(25),
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE bank_accounts (
 account_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id NUMBER NOT NULL REFERENCES customers(customer_id),
 account_number VARCHAR2(24) NOT NULL UNIQUE,
 account_type VARCHAR2(10) NOT NULL CHECK(account_type IN ('SAVINGS','CURRENT')),
 balance NUMBER(14,2) DEFAULT 0 NOT NULL CHECK(balance >= 0),
 status VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL CHECK(status IN ('ACTIVE','CLOSED')),
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE bank_transactions (
 transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id NUMBER NOT NULL REFERENCES bank_accounts(account_id),
 transaction_type VARCHAR2(12) NOT NULL CHECK(transaction_type IN ('DEPOSIT','WITHDRAWAL','TRANSFER_IN','TRANSFER_OUT')),
 amount NUMBER(14,2) NOT NULL CHECK(amount > 0),
 description VARCHAR2(250),
 reference_number VARCHAR2(40) NOT NULL,
 related_account_id NUMBER REFERENCES bank_accounts(account_id),
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT uq_tx_ref_account UNIQUE(reference_number, account_id)
);
CREATE TABLE balance_audit_log (
 audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id NUMBER NOT NULL REFERENCES bank_accounts(account_id),
 old_balance NUMBER(14,2) NOT NULL,
 new_balance NUMBER(14,2) NOT NULL,
 action_type VARCHAR2(30) NOT NULL,
 changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_accounts_customer ON bank_accounts(customer_id);
CREATE INDEX ix_tx_account_date ON bank_transactions(account_id, created_at);
CREATE INDEX ix_audit_account_date ON balance_audit_log(account_id, changed_at);
CREATE OR REPLACE VIEW v_fintrust_accounts AS
SELECT a.account_id,a.account_number,a.account_type,a.balance,a.status,a.created_at,
       c.customer_id,c.full_name,c.email
FROM bank_accounts a JOIN customers c ON c.customer_id=a.customer_id;
